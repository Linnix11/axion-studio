const assert = require('assert'); const f = require('./outils.cjs')
let r = f('<link href="/wp-content/themes/x.css"><form class="wpcf7"><input></form> Demande de devis <a href="https://calendly.com/plombier">RDV</a>')
assert.strictEqual(r.outils, 'WordPress, Calendly, formulaire de contact')
assert.strictEqual(r.pistes, 'préparer automatiquement les demandes de devis reçues par le site ; relier les rendez-vous pris sur Calendly au fichier client et aux rappels')
r = f('<script src="https://cdn.shopify.com/s.js"></script><form action="/search" role="search"></form><a href="https://wa.me/336">')
assert.strictEqual(r.outils, 'Shopify, WhatsApp')
assert.strictEqual(r.pistes, 'mettre à jour commandes, stock et suivi client automatiquement ; répondre automatiquement aux questions les plus fréquentes')
r = f('<p>Bienvenue</p>')
assert.deepStrictEqual(r, { outils: '', pistes: 'ajouter un formulaire ou une prise de rendez-vous en ligne reliés à vos outils' })
r = f('<form method="post"></form><script src="//js.hs-scripts.com/1.js"></script>')
assert.strictEqual(r.outils, 'HubSpot, formulaire de contact'); assert.strictEqual(r.pistes, '')
assert.deepStrictEqual(f(null).outils, '')
console.log('ok')
